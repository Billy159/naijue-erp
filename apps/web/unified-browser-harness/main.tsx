const root=document.getElementById('unified-root')!,log=document.getElementById('calls')!,entry=document.getElementById('unified-entry')!,status=document.getElementById('harness-status')!;
const harness=mountUnifiedProfileSession(root,call=>{log.textContent=`${call.method} ${call.path} · SYNTHETIC ONLY\n${log.textContent??''}`.slice(0,10000);});
const detachProfileTools=mountReviewProfileToolbar(document.getElementById('review-profile-tools')!,harness,profile=>{
 root.hidden=true;entry.hidden=false;log.textContent='';
 (document.getElementById('read-failure') as HTMLSelectElement).value='none';(document.getElementById('transaction-failure') as HTMLSelectElement).value='none';(document.getElementById('prepare-delay') as HTMLInputElement).checked=false;
 status.textContent=profile==='transfer-readonly'?'合成只读调拨配置已选择；旧会话已结束，请重新进入。不是正式角色授权。':'标准合成交易配置已选择；旧会话已结束，请重新进入。';
});
async function enter(){const button=document.getElementById('enter') as HTMLButtonElement;button.disabled=true;try{if(await harness.enter()){entry.hidden=true;root.hidden=false;status.textContent=harness.getSnapshot().profile==='transfer-readonly'?'合成只读调拨配置；同一业务应用、无正式授权。':'同一业务应用、同一合成身份；刷新清空所有合成单据。';}else status.textContent='未能进入；请先处理当前未保存内容或原操作回执。';}finally{button.disabled=false;}}
document.getElementById('enter')!.addEventListener('click',()=>{void enter();});
document.getElementById('reenter')!.addEventListener('click',()=>{void enter();});
document.getElementById('home')!.addEventListener('click',()=>{void harness.app.controller.navigate(null);});
document.getElementById('revoke')!.addEventListener('click',()=>{void harness.revoke().then(()=>{root.hidden=true;entry.hidden=false;status.textContent='合成身份已清除；可重新进入，无需密码。';});});
document.getElementById('show-session-layout')!.addEventListener('change',event=>root.classList.toggle('show-synthetic-session',(event.target as HTMLInputElement).checked));
document.getElementById('read-failure')!.addEventListener('change',event=>harness.transport.setNextReadFailure((event.target as HTMLSelectElement).value as SyntheticReadFailure));
document.getElementById('read-delay')!.addEventListener('click',()=>harness.transport.setNextReadDelay(3000));
document.getElementById('transaction-failure')!.addEventListener('change',event=>harness.transport.setTransactionFailure((event.target as HTMLSelectElement).value as SyntheticTransactionFailure));
document.getElementById('prepare-delay')!.addEventListener('change',event=>harness.transport.setPreparationDelay((event.target as HTMLInputElement).checked?3000:0));
window.addEventListener('pagehide',()=>{detachProfileTools();harness.dispose();},{once:true});
