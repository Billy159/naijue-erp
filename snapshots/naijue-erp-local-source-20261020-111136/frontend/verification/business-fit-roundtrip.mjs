vm.runInContext(code.slice(readerStart,readerEnd)+';globalThis.readDoc=doc;',reader);
const row={id:'sale-uuid',number:'V2-SALE',document_type:'SALE',version:1,current_revision:'rev',status:'UNAUDITED',body:{...sale,header:{...sale.header,source_payload:{}}},history:[]};
const reopened=reader.readDoc(row);
assert.equal(reopened.lines[1].referenceCents,10000,'saved discount remains editable against its original reference price');
assert.equal(reopened.lines[1].discountTenths,90);assert.equal(reopened.lines[1].priceCents,9000);
const historical=structuredClone(row);delete historical.body.lines[1].source_payload.v2_reference_price_cents;
assert.equal(reader.readDoc(historical,false).lines[1].referenceCents,null,'missing historical reference prices are not invented from current product prices');
console.log('Sales/transfer fit SKU roundtrip, immutable canonical identity and discount reference snapshot: PASS');
