assert.equal(b.skuByCell['white|size-165'],'sku-b');
assert.equal(b.barcodes['white|size-165'].current,'CODE-B');
assert.equal(b.stock.warehouse[0][0],-2);
assert.deepEqual(p,original,'fit projection never mutates source identity or barcode facts');
assert.equal(sourceCode(b),'REAL-STYLE');
assert.equal(b.id,fitViewId(p,'B'));
const d={lines:[]};M.add(d,M.line(p,0,0,1,10000));M.add(d,M.line(b,0,0,2,10000));
assert.equal(d.lines.length,2,'same style/color/size with different fits cannot merge');
const code=fs.readFileSync(new URL('../real-data-bridge.mjs',import.meta.url),'utf8'),start=code.indexOf('function bodyFrom('),end=code.indexOf('const pending=',start);
