assert.equal(read.q[p.id+'|0|0'],1);
assert.equal(read.q[b.id+'|0|0'],2,'saved transfer keeps separate fit SKU quantities when reopened');
assert.equal(read.items.length,2);
assert(sale.lines.every(l=>l.source_payload.v2_reference_price_cents===10000),'known reference price is retained in the saved line snapshot');
p.legacySizeRecords=[{id:'size-165',name:'165/S'}];b.legacySizeRecords=p.legacySizeRecords;
const reader=vm.createContext({D:{products:[p]},C,fitViewId,copy:structuredClone,Adapter,canonicalHall:x=>x,refs:{halls:[]},by:()=>null,bridge:{skus:new Map([['sku-a',{fitId:'A'}],['sku-b',{fitId:'B'}]]),docs:new Map()},SALES_SUMMARY:{categorySnapshot:()=>({})},historyActor:()=>({name:'回归员工'})});
