import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import {createRequire} from 'node:module';
import {fitView,fitViewId,sourceCode} from '../business-product-view.mjs';
import * as Adapter from '../legacy-adapter.mjs';
const {transfer}=Adapter;
const require=createRequire(import.meta.url),K=require('../sales-core.js'),M=require('../sales-model.js');
const C={fit:id=>({id,name:id+'版'})};
const p={id:'REAL-STYLE',uuid:'product-uuid',displayId:'REAL-STYLE',baseFitId:'A',fitId:'A',fit:'A版',name:'商品',price:100,colorIds:['white'],colors:['白色'],sizeIds:['size-165'],sizes:['165/S'],skuByCell:{'white|size-165':'sku-a'},skuByFitCell:{'white|A|size-165':'sku-a','white|B|size-165':'sku-b'},barcodes:{'white|size-165':{skuId:'sku-a',current:'CODE-A',history:[],fitId:'A'},'white|B|size-165':{skuId:'sku-b',current:'CODE-B',history:['OLD-B'],fitId:'B'}},stock:{warehouse:[[3]]}};
