 const commits=[],runtimeServer=structuredClone(runtimeBase);
 const commitRuntime=async(type,record)=>{
  commits.push({type,id:record.id,enabled:record.enabled});
  const index=runtimeServer[type].findIndex(x=>x.id===record.id),previous=runtimeServer[type][index];
  const changes=Object.keys(record).filter(field=>JSON.stringify(previous?.[field])!==JSON.stringify(record[field])).map(field=>({field,before:previous?.[field]??null,after:structuredClone(record[field])}));
  if(index<0)runtimeServer[type].push(structuredClone(record));else runtimeServer[type][index]=structuredClone(record);
  runtimeServer.revision++;
  runtimeServer.audit.push({type,target:record.id,action:record.enabled===false?'停用':previous?'修改':'新增',changes});
  return {ok:true};
 };
